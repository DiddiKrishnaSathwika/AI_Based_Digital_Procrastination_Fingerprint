def test_TC_DB_06_auth_migration_preserves_accounts_and_removes_email_schema(env):
    """Removing verification metadata preserves legacy users and their passwords."""
    _, user_id = env.make_user("legacy@x.com")
    env.insert_rows(
        user_id,
        [("2026-11-01T10:00", "VS Code", "Coding", 5, "Focused")],
    )
    with env.connect() as conn:
        conn.execute(
            "ALTER TABLE users ADD COLUMN is_verified INTEGER NOT NULL DEFAULT 1"
        )
        conn.execute("ALTER TABLE users ADD COLUMN verified_at TEXT")
        conn.execute(
            """
            CREATE TABLE email_verification_tokens (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id),
                token_hash TEXT NOT NULL,
                expires_at TEXT NOT NULL,
                used INTEGER NOT NULL DEFAULT 0
            )
            """
        )
        conn.execute(
            """
            CREATE TABLE password_reset_tokens (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id),
                token_hash TEXT NOT NULL,
                expires_at TEXT NOT NULL,
                used INTEGER DEFAULT 0
            )
            """
        )
        conn.execute("UPDATE users SET is_verified = 0 WHERE id = %s", (user_id,))

    appmod.init_db()
    appmod.init_db()

    user_columns = {
        row["column_name"]
        for row in env.query(
            """
            SELECT column_name
            FROM information_schema.columns
            WHERE table_schema = current_schema() AND table_name = 'users'
            """
        )
    }
    tables = {
        row["table_name"]
        for row in env.query(
            """
            SELECT table_name
            FROM information_schema.tables
            WHERE table_schema = current_schema()
            """
        )
    }
    assert "is_verified" not in user_columns
    assert "verified_at" not in user_columns
    assert "password_reset_tokens" not in tables
    assert "email_verification_tokens" not in tables
    assert env.query("SELECT id FROM users WHERE id = %s", (user_id,))
    assert env.query("SELECT id FROM activity WHERE user_id = %s", (user_id,))

    fresh_client = appmod.app.test_client()
    assert fresh_client.post(
        "/api/auth/login",
        json={"email": "legacy@x.com", "password": "password123"},
    ).status_code == 200
