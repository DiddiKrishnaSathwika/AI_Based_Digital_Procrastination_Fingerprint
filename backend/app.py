def init_db():
    """Create and initialize the PostgreSQL database tables."""

    with psycopg.connect(DATABASE_URL) as conn:

        # Users
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                full_name TEXT NOT NULL DEFAULT '',
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                is_verified INTEGER NOT NULL DEFAULT 0,
                verified_at TEXT,
                created_at TEXT NOT NULL
            )
        """)

        # Safely migrate existing user columns
        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS full_name TEXT NOT NULL DEFAULT ''
        """)

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS is_verified INTEGER NOT NULL DEFAULT 1
        """)

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS verified_at TEXT
        """)

        # Password reset tokens
        conn.execute("""
            CREATE TABLE IF NOT EXISTS password_reset_tokens (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id),
                token_hash TEXT NOT NULL,
                expires_at TEXT NOT NULL,
                used INTEGER DEFAULT 0
            )
        """)

        # Email verification tokens
        conn.execute("""
            CREATE TABLE IF NOT EXISTS email_verification_tokens (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id),
                token_hash TEXT NOT NULL,
                expires_at TEXT NOT NULL,
                used INTEGER NOT NULL DEFAULT 0
            )
        """)

        # Activity records
        conn.execute("""
            CREATE TABLE IF NOT EXISTS activity (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                timestamp TEXT NOT NULL,
                application TEXT NOT NULL,
                category TEXT NOT NULL,
                duration_min REAL NOT NULL,
                task_type TEXT,
                task_difficulty TEXT,
                idle_seconds INTEGER DEFAULT 0,
                notifications INTEGER DEFAULT 0,
                focus_level TEXT NOT NULL,
                source TEXT DEFAULT 'synthetic',
                user_id INTEGER REFERENCES users(id)
            )
        """)

        conn.execute("""
            ALTER TABLE activity
            ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES users(id)
        """)

        # Active tasks
        conn.execute("""
            CREATE TABLE IF NOT EXISTS active_tasks (
                user_id INTEGER PRIMARY KEY REFERENCES users(id),
                task_type TEXT NOT NULL,
                task_difficulty TEXT NOT NULL,
                started_at TEXT NOT NULL,
                is_active INTEGER NOT NULL DEFAULT 1
            )
        """)

        # Desktop collector authentication tokens
        conn.execute("""
            CREATE TABLE IF NOT EXISTS collector_tokens (
                user_id INTEGER PRIMARY KEY REFERENCES users(id),
                token_hash TEXT NOT NULL,
                created_at TEXT NOT NULL,
                is_active INTEGER NOT NULL DEFAULT 1
            )
        """)

        # Activity lookup index
        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_activity_user_id
            ON activity(user_id)
        """)



