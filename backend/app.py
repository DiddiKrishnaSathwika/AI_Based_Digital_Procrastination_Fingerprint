@app.route("/api/analytics")
@login_required
def api_analytics():
    db = get_db()
    rows = fetch_all_rows(db, session["user_id"])

    focus_by_day = {}
    distract_by_hour = {h: 0 for h in range(24)}
    cat_usage = {}
    difficulty_distract = {"Low": 0, "Medium": 0, "High": 0}
    switch_by_day = {}
    focus_durations = []

    for r in rows:
        day = r["timestamp"][:10]
        hour = int(r["timestamp"][11:13])
        cat_usage[r["category"]] = cat_usage.get(r["category"], 0) + r["duration_min"]
        switch_by_day[day] = switch_by_day.get(day, 0) + 1
        if r["focus_level"] == "Focused":
            focus_by_day.setdefault(day, {"focus": 0, "total": 0})
            focus_by_day[day]["focus"] += r["duration_min"]
            focus_durations.append(r["duration_min"])
        if r["focus_level"] == "Distracted":
            distract_by_hour[hour] += 1
            if r["task_difficulty"] in difficulty_distract:
                difficulty_distract[r["task_difficulty"]] += 1
        focus_by_day.setdefault(day, {"focus": 0, "total": 0})
        focus_by_day[day]["total"] += r["duration_min"]

    focus_over_time = [
        {"date": d[5:], "focus_score": round((v["focus"] / v["total"]) * 100) if v["total"] else 0}
        for d, v in sorted(focus_by_day.items())
    ]
    distraction_by_time = [
        {"hour": f"{h:02d}:00", "events": distract_by_hour[h]} for h in range(24) if distract_by_hour[h] or 6 <= h <= 23
    ]
    category_usage = [{"category": k, "minutes": round(v)} for k, v in sorted(cat_usage.items(), key=lambda x: -x[1])]
    switching_frequency = [{"date": d[5:], "switches": v} for d, v in sorted(switch_by_day.items())]

    buckets = {"0-10": 0, "10-20": 0, "20-30": 0, "30-40": 0, "40+": 0}
    for d in focus_durations:
        if d < 10: buckets["0-10"] += 1
        elif d < 20: buckets["10-20"] += 1
        elif d < 30: buckets["20-30"] += 1
        elif d < 40: buckets["30-40"] += 1
        else: buckets["40+"] += 1
    focus_distribution = [{"bucket": k, "count": v} for k, v in buckets.items()]

    task_vs_distraction = [{"difficulty": k, "distractions": v} for k, v in difficulty_distract.items()]

    daily_trend = [
        {"date": d[5:], "productivity": round((v["focus"] / v["total"]) * 100) if v["total"] else 0}
        for d, v in sorted(focus_by_day.items())
    ]

    return jsonify({
        "focus_over_time": focus_over_time,
        "distraction_by_time": distraction_by_time,
        "category_usage": category_usage,
        "switching_frequency": switching_frequency,
        "focus_distribution": focus_distribution,
        "task_vs_distraction": task_vs_distraction,
        "daily_trend": daily_trend,
        "distraction_by_hour": [{"hour": f"{h:02d}", "events": distract_by_hour[h]} for h in range(24)],
        "data_label": "Real-Time Activity Data",
    })


