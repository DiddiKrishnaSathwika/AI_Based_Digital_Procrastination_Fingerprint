# INTERVENTIONS (rule-based selection from recorded activity)
# ----------------------------------------------------------------------------
# All thresholds are design heuristics chosen by the project team. They have not
# been validated against user outcomes. Only fields the collector fills are used:
# application, category, timestamp, duration_min, focus_level.
INTERVENTION_RULES = {
    "min_tracked_records": 20,        # Focused+Distracted records needed before suggesting anything
    "min_distraction_records": 3,
    "micro_break_streak_ratio": 0.7,  # current streak / average run
    "top_app_share": 0.30,            # share of distracted minutes held by one application
    "top_app_min_distract_min": 5.0,
    "switch_window": 12,              # latest records examined
    "switch_threshold": 8,            # application changes in that window
    "sprint_min_runs": 3,
    "sprint_avg_run_below": 25.0,
    "sprint_len_min": 5,
    "sprint_len_max": 25,
    "hour_share": 0.25,               # share of distraction records in the busiest hour
    "hour_min_records": 5,
    "max_suggestions": 4,
}


def _focus_runs(rows):
    """Consecutive Focused records form a run; any other record closes it (same rule as the prediction)."""
    runs, cur = [], 0.0
    for r in rows:
        if r["focus_level"] == "Focused":
            cur += max(0.0, float(r["duration_min"] or 0))
        else:
            if cur > 0:
                runs.append(cur)
            cur = 0.0
    if cur > 0:
        runs.append(cur)
    streak = 0.0
    for r in reversed(rows):
        if r["focus_level"] != "Focused":
            break
        streak += max(0.0, float(r["duration_min"] or 0))
    return runs, streak


def select_interventions(rows):
    """
    Return a ranked list of interventions whose trigger conditions are met by
    the user's recorded activity. Each item carries the evidence (real numbers)
    that triggered it. rows must be ordered by timestamp ascending.
    """
    cfg = INTERVENTION_RULES
    tracked = [r for r in rows if r["focus_level"] in ("Focused", "Distracted")]
    distracted = [r for r in rows if r["focus_level"] == "Distracted"]

    if len(tracked) < cfg["min_tracked_records"] or len(distracted) < cfg["min_distraction_records"]:
        return [{
            "rule_id": "insufficient_data",
            "title": "Keep Tracking",
            "description": "There is not yet enough recorded activity to select suggestions for you.",
            "reason": (
                f"Needs at least {cfg['min_tracked_records']} Focused/Distracted records and "
                f"{cfg['min_distraction_records']} distraction records; found {len(tracked)} and {len(distracted)}."
            ),
            "priority": 0,
        }]

    suggestions = []
    runs, streak = _focus_runs(rows)
    avg_run = (sum(runs) / len(runs)) if runs else None
    pred = predict_distraction(rows)

    # 1. Micro Break: prediction risk HIGH, or current streak close to the usual run length
    near_end = (
        avg_run is not None and streak > 0
        and streak >= cfg["micro_break_streak_ratio"] * avg_run
    )
    if pred["risk_level"] == "HIGH" or near_end:
        parts = [f"Predicted distraction risk is {pred['risk_level']} ({pred['distraction_probability']}%)."]
        if avg_run is not None:
            parts.append(
                f"Your current uninterrupted focused streak is {streak:.1f} min "
                f"against an average run of {avg_run:.1f} min."
            )
        suggestions.append({
            "rule_id": "micro_break", "title": "Micro Break",
            "description": "Take a 5-minute break away from the screen.",
            "reason": " ".join(parts),
            # A HIGH prediction is time-sensitive, so it always ranks first (ties keep insertion order).
            "priority": 1.0 if pred["risk_level"] == "HIGH" else round((pred["distraction_probability"] or 0) / 100.0, 2),
        })

    # 2. Remove Distraction: one application holds a large share of distracted time
    app_min, app_n = {}, {}
    for r in distracted:
        a = r["application"]
        app_min[a] = app_min.get(a, 0.0) + float(r["duration_min"] or 0)
        app_n[a] = app_n.get(a, 0) + 1
    total_d = sum(app_min.values())
    if total_d >= cfg["top_app_min_distract_min"]:
        top_app = max(app_min, key=app_min.get)
        share = app_min[top_app] / total_d
        if share >= cfg["top_app_share"]:
            suggestions.append({
                "rule_id": "remove_distraction", "title": "Remove Distraction",
                "description": f"Temporarily close or block {top_app}.",
                "reason": (
                    f"{top_app} accounts for {share * 100:.0f}% of your recorded distracted time "
                    f"({app_min[top_app]:.1f} of {total_d:.1f} min across {app_n[top_app]} records)."
                ),
                "priority": round(min(1.0, share), 2),
            })

    # 3. Reduce App Switching: many application changes in the latest records
    recent = rows[-cfg["switch_window"]:]
    switches = sum(
        1 for i in range(1, len(recent)) if recent[i - 1]["application"] != recent[i]["application"]
    )
    if switches >= cfg["switch_threshold"]:
        suggestions.append({
            "rule_id": "reduce_switching", "title": "Reduce App Switching",
            "description": "Keep one window in front for a set period and batch quick checks of other apps.",
            "reason": f"{switches} application changes occurred in your latest {len(recent)} activity records.",
            "priority": round(min(1.0, switches / max(1, len(recent) - 1)), 2),
        })

    # 4. Focus Sprint: short typical uninterrupted runs
    if len(runs) >= cfg["sprint_min_runs"] and avg_run < cfg["sprint_avg_run_below"]:
        sprint = int(min(cfg["sprint_len_max"], max(cfg["sprint_len_min"], round(avg_run))))
        suggestions.append({
            "rule_id": "focus_sprint", "title": "Focus Sprint",
            "description": f"Start a {sprint}-minute focused session on a single task, then pause.",
            "reason": (
                f"Your recorded uninterrupted focus runs average {avg_run:.1f} min across {len(runs)} runs; "
                f"a {sprint}-minute sprint is sized to what you have actually sustained."
            ),
            "priority": round(max(0.0, (cfg["sprint_avg_run_below"] - avg_run) / cfg["sprint_avg_run_below"]), 2),
        })

    # 5. Protect Risky Hour: distraction records cluster in one clock hour
    by_hour = {}
    for r in distracted:
        hh = r["timestamp"][11:13]
        if hh.isdigit():
            by_hour[int(hh)] = by_hour.get(int(hh), 0) + 1
    if by_hour:
        top_h = max(by_hour, key=by_hour.get)
        k, n = by_hour[top_h], sum(by_hour.values())
        if k >= cfg["hour_min_records"] and k / n >= cfg["hour_share"]:
            end_h = (top_h + 1) % 24
            suggestions.append({
                "rule_id": "risky_hour", "title": "Protect Your Risky Hour",
                "description": f"Close distracting applications before {top_h:02d}:00 and keep that hour for one task.",
                "reason": f"{k} of your {n} recorded distraction records fall between {top_h:02d}:00 and {end_h:02d}:00.",
                "priority": round(k / n, 2),
            })

    if not suggestions:
        return [{
            "rule_id": "no_pattern", "title": "No Strong Pattern Detected",
            "description": "None of the suggestion conditions are currently met by your recorded activity.",
            "reason": f"Evaluated {len(tracked)} tracked records including {len(distracted)} distraction records.",
            "priority": 0,
        }]

    suggestions.sort(key=lambda x: x["priority"], reverse=True)
    return suggestions[: cfg["max_suggestions"]]



def build_fingerprint(rows):
    """
    Builds a personalized digital procrastination fingerprint
    using recorded real-time activity.
    No synthetic statistics or assumed behavioral patterns.
    """

    if not rows:
        return {
            "typical_focus_duration_min": None,
            "typical_distraction_window": None,
            "app_switching_pattern": "Insufficient data",
            "most_frequent_distraction": "Insufficient data",
            "most_used_applications": [],
            "most_risky_task": "Insufficient data",
            "most_risky_time": "Insufficient data",
            "average_recovery_time_min": None,
            "productive_time_min": 0,
            "distracted_time_min": 0,
            "productive_percentage": None,
            "distraction_percentage": None,
            "application_switches": 0,
            "narrative": (
                "Not enough activity has been recorded to build your "
                "digital procrastination fingerprint. Continue tracking "
                "your activities to discover your behavioral patterns."
            ),
            "label": "Insufficient real-time activity data"
        }

    # Aggregate application usage and activity duration
    app_usage = {}
    distraction_apps = {}
    distraction_categories = {}
    risky_tasks = {}
    risky_hours = {}

    productive_time = 0.0
    distracted_time = 0.0

    focus_sessions = []
    current_focus_session = 0.0

    distraction_episodes = []
    current_distraction_episode = 0.0

    application_switches = 0

    previous_app = None

    for r in rows:
        duration = max(0.0, float(r["duration_min"] or 0))

        application = r["application"] or "Unknown"
        category = r["category"] or "Other"
        focus_level = r["focus_level"] or "Unknown"

        # Application usage duration
        app_usage[application] = (
            app_usage.get(application, 0.0) + duration
        )

        # Actual application changes
        if previous_app is not None and previous_app != application:
            application_switches += 1

        previous_app = application

        # Productive activity
        if focus_level == "Focused":
            productive_time += duration
            current_focus_session += duration

            if current_distraction_episode > 0:
                distraction_episodes.append(
                    current_distraction_episode
                )
                current_distraction_episode = 0.0

        # Distracted activity
        elif focus_level == "Distracted":
            distracted_time += duration
            current_distraction_episode += duration

            distraction_apps[application] = (
                distraction_apps.get(application, 0) + 1
            )

            distraction_categories[category] = (
                distraction_categories.get(category, 0) + 1
            )

            task = r["task_difficulty"]

            if task:
                risky_tasks[task] = (
                    risky_tasks.get(task, 0) + 1
                )

            timestamp = r["timestamp"]

            try:
                hour = datetime.fromisoformat(
                    timestamp
                ).hour

                risky_hours[hour] = (
                    risky_hours.get(hour, 0) + 1
                )
            except (ValueError, TypeError):
                pass

        # End an estimated focus session
        else:
            if current_focus_session > 0:
                focus_sessions.append(current_focus_session)
                current_focus_session = 0.0

            if current_distraction_episode > 0:
                distraction_episodes.append(
                    current_distraction_episode
                )
                current_distraction_episode = 0.0

    # Include final incomplete segments
    if current_focus_session > 0:
        focus_sessions.append(current_focus_session)

    if current_distraction_episode > 0:
        distraction_episodes.append(
            current_distraction_episode
        )

    # Average estimated focus duration
    avg_focus = (
        round(sum(focus_sessions) / len(focus_sessions), 1)
        if focus_sessions else None
    )

    # Average distraction episode duration.
    # This is a proxy, not verified time to recover focus.
    avg_distraction = (
        round(
            sum(distraction_episodes) / len(distraction_episodes),
            1
        )
        if distraction_episodes else None
    )

    # Productive and distracted time distribution
    total_time = productive_time + distracted_time

    productive_percentage = (
        round(productive_time / total_time * 100, 1)
        if total_time > 0 else None
    )

    distraction_percentage = (
        round(distracted_time / total_time * 100, 1)
        if total_time > 0 else None
    )

    # Most frequent distraction category
    top_distraction = (
        max(distraction_categories, key=distraction_categories.get)
        if distraction_categories else "Insufficient data"
    )

    # Most-used applications by recorded duration
    most_used_apps = sorted(
        [
            {
                "application": app,
                "duration_min": round(duration, 2)
            }
            for app, duration in app_usage.items()
        ],
        key=lambda x: x["duration_min"],
        reverse=True
    )[:5]

    # Most frequent distraction application
    top_distraction_app = (
        max(distraction_apps, key=distraction_apps.get)
        if distraction_apps else None
    )

    # Most commonly associated task difficulty
    risky_diff = (
        max(risky_tasks, key=risky_tasks.get)
        if risky_tasks else None
    )

    # Most frequently recorded distraction hour
    risky_hour = (
        max(risky_hours, key=risky_hours.get)
        if risky_hours else None
    )

    # Switching frequency based on actual changes
    if len(rows) < 3:
        switching_pattern = "Insufficient data"
    elif application_switches >= 20:
        switching_pattern = "High"
    elif application_switches >= 8:
        switching_pattern = "Moderate"
    else:
        switching_pattern = "Low"

    # Estimated focus window
    focus_window = (
        [round(avg_focus), round(avg_focus) + 5]
        if avg_focus is not None else None
    )

    # Format the highest-risk hour without exceeding midnight
    risky_time = (
        f"{risky_hour:02d}:00 - {(risky_hour + 2) % 24:02d}:00"
        if risky_hour is not None else "Insufficient data"
    )

    # Generate a data-supported behavioral summary
    if avg_focus is None:
        narrative = (
            "Your recorded history does not yet contain enough "
            "focused activity to estimate your typical focus duration."
        )
    else:
        narrative = (
            f"Your estimated average uninterrupted focused activity "
            f"session is {avg_focus} minutes."
        )

    if top_distraction_app:
        narrative += (
            f" {top_distraction_app} is your most frequently "
            f"recorded distraction application."
        )

    if risky_diff:
        narrative += (
            f" Distraction records occur most frequently during "
            f"{risky_diff.lower()}-difficulty tasks."
        )

    if risky_hour is not None:
        narrative += (
            f" Your most frequently recorded distraction hour "
            f"is {risky_hour:02d}:00."
        )

    narrative += (
        " These patterns describe recorded application activity, "
        "not verified attention or concentration."
    )

    return {
        "typical_focus_duration_min": avg_focus,
        "typical_distraction_window": focus_window,
        "app_switching_pattern": switching_pattern,
        "most_frequent_distraction": top_distraction,
        "most_used_applications": most_used_apps,
        "most_risky_task": risky_diff or "Insufficient data",
        "most_risky_time": risky_time,
        "average_recovery_time_min": avg_distraction,
        "productive_time_min": round(productive_time, 2),
        "distracted_time_min": round(distracted_time, 2),
        "productive_percentage": productive_percentage,
        "distraction_percentage": distraction_percentage,
        "application_switches": application_switches,
        "narrative": narrative,
        "label": "Generated from Real-Time Activity Data"
    }



