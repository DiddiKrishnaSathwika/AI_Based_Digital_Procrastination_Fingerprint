@app.route("/api/activity", methods=["GET", "POST"])
def api_activity():

    collector_user_id = get_collector_user_id()

    if "user_id" in session:
        user_id = session["user_id"]
    elif collector_user_id is not None:
        user_id = collector_user_id
    else:
        return jsonify({
            "success": False,
            "message": "Please log in or provide a valid collector token."
        }), 401

    db = get_db()

    if request.method == "POST":
        d = request.get_json(force=True)

        # Records posted from the logged-in browser (Data Collection form) are
        # tagged 'manual'; records posted by the desktop collector with its
        # Bearer token keep the 'realtime' tag.
        record_source = "manual" if "user_id" in session else "realtime"

        db.execute(
            """
            INSERT INTO activity (
                timestamp, application, category, duration_min,
                task_type, task_difficulty, idle_seconds,
                notifications, focus_level, source, user_id
            )
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            """,
            (
                d.get("timestamp") or datetime.now().isoformat(timespec="minutes"),
                d.get("application", "Unknown"),
                d.get("category", "Other"),
                float(d.get("duration_min", 0)),
                d.get("task_type"),
                d.get("task_difficulty"),
                int(d.get("idle_seconds", 0)),
                int(d.get("notifications", 0)),
                d.get("focus_level") or "Focused",
                record_source,
                user_id
            )
        )

        db.commit()
        return jsonify({"status": "created", "source": record_source}), 201

    limit = min(int(request.args.get("limit", 60)), 500)
    filt = request.args.get("filter", "All")

    q = "SELECT * FROM activity WHERE user_id = %s"
    params = [user_id]

    if filt != "All":
        q += " AND focus_level = %s"
        params.append(filt)

    q += " ORDER BY timestamp DESC LIMIT %s"
    params.append(limit)

    rows = db.execute(q, params).fetchall()

    return jsonify([dict(r) for r in reversed(rows)])

