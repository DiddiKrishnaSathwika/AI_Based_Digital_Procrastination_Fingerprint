def generate_collector_token():
    """
    Generate a secure token and its SHA-256 hash.
    The raw token is returned only for one-time delivery.
    """
    token = secrets.token_urlsafe(32)
    token_hash = hashlib.sha256(token.encode("utf-8")).hexdigest()

    return token, token_hash

def get_collector_user_id():
    """
    Validate the desktop collector's Bearer token
    and return the associated user ID.
    """
    auth_header = request.headers.get("Authorization", "")

    if not auth_header.startswith("Bearer "):
        return None

    token = auth_header.split(" ", 1)[1].strip()

    if not token:
        return None

    token_hash = hashlib.sha256(
        token.encode("utf-8")
    ).hexdigest()

    db = get_db()

    row = db.execute(
        """
        SELECT user_id
        FROM collector_tokens
        WHERE token_hash = %s AND is_active = 1
        """,
        (token_hash,)
    ).fetchone()

    return row["user_id"] if row else None


