def predict_distraction(rows):
    """
    Personalized rule-based distraction prediction.
    Uses estimated focus sessions from consecutive activity records.
    Not a trained or statistically validated ML model.
    """

    if not rows:
        return {
            "distraction_probability": None,
            "risk_level": "NO DATA",
            "predicted_window_min": None,
            "confidence": None,
            "factors": [
                "Start tracking your activity to build your personal distraction fingerprint."
            ],
            "label": "Insufficient activity data"
        }

    focus_sessions = []
    current_run = 0.0

    total_focus_time = 0.0
    total_distracted_time = 0.0

    # Group consecutive focused records into estimated sessions
    for r in rows:
        duration = max(0.0, float(r["duration_min"] or 0))

        if r["focus_level"] == "Focused":
            current_run += duration
            total_focus_time += duration

        else:
            if current_run > 0:
                focus_sessions.append(current_run)
                current_run = 0.0

            if r["focus_level"] == "Distracted":
                total_distracted_time += duration

    if current_run > 0:
        focus_sessions.append(current_run)

    # Average estimated focus-session duration
    avg_focus = (
        sum(focus_sessions) / len(focus_sessions)
        if focus_sessions else 25.0
    )

    # Current uninterrupted focused streak
    current_focus_streak = 0.0

    for r in reversed(rows):
        if r["focus_level"] != "Focused":
            break

        current_focus_streak += max(
            0.0, float(r["duration_min"] or 0)
        )

    # Recent application changes
    recent_rows = rows[-12:]
    recent_switches = 0

    for i in range(1, len(recent_rows)):
        if (
            recent_rows[i - 1]["application"]
            != recent_rows[i]["application"]
        ):
            recent_switches += 1

    # Duration-weighted historical distraction ratio
    total_tracked_time = total_focus_time + total_distracted_time

    distraction_ratio = (
        total_distracted_time / total_tracked_time
        if total_tracked_time > 0 else 0
    )

    # Current progress toward the historical average
    focus_ratio = current_focus_streak / max(avg_focus, 1)

    history_score = distraction_ratio * 35
    switch_score = min(recent_switches * 4, 24)
    focus_score = min(focus_ratio * 25, 25)

    probability = round(
        min(95, max(
            5,
            15 + history_score + switch_score + focus_score
        ))
    )

    if probability >= 70:
        risk = "HIGH"
    elif probability >= 45:
        risk = "MODERATE"
    else:
        risk = "LOW"

    remaining_minutes = max(
        1,
        round(avg_focus - current_focus_streak)
    )

    predicted_window = [
        remaining_minutes,
        remaining_minutes + 5
    ]

    factors = []

    if focus_sessions:
        factors.append(
            f"Average estimated uninterrupted focus session: {avg_focus:.1f} minutes."
        )

    if current_focus_streak > 0 and focus_ratio >= 0.7:
        factors.append(
            "Current focused activity is approaching your historical average session duration."
        )

    if recent_switches >= 4:
        factors.append(
            f"{recent_switches} application changes detected in the latest activity records."
        )

    if distraction_ratio >= 0.4:
        factors.append(
            "Historical recorded activity contains a relatively high proportion of distracted time."
        )

    if not factors:
        factors.append(
            "No strong distraction pattern has been detected in the available activity history."
        )

    factors.append(
        "This estimate uses a rule-based heuristic, not a trained ML model."
    )

    return {
        "distraction_probability": probability,
        "risk_level": risk,
        "predicted_window_min": predicted_window,
        "confidence": None,
        "factors": factors,
        "label": "Prototype Prediction (personalized rule-based heuristic, not a trained ML model)"
    }






