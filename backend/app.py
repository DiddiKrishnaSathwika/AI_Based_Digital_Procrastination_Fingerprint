@app.route("/api/eda")
@login_required
def api_eda():
    db = get_db()
    rows = fetch_all_rows(db, session["user_id"])
    m = compute_metrics(rows)
    cat_counts = {}
    for r in rows:
        cat_counts[r["category"]] = cat_counts.get(r["category"], 0) + 1
    most_common_cat = max(cat_counts, key=cat_counts.get) if cat_counts else "Coding"

    features = ["duration_min", "idle_seconds", "notifications"]
    numeric = {f: [r[f] for r in rows] for f in features}

    def corr(a, b):
        n = len(a)
        if n < 2:
            return 0
        ma, mb = sum(a) / n, sum(b) / n
        cov = sum((x - ma) * (y - mb) for x, y in zip(a, b))
        va = math.sqrt(sum((x - ma) ** 2 for x in a))
        vb = math.sqrt(sum((y - mb) ** 2 for y in b))
        return round(cov / (va * vb), 2) if va and vb else 0

    labels = ["Duration", "Idle Time", "Notifications"]
    matrix = [[corr(numeric[f1], numeric[f2]) for f2 in features] for f1 in features]

    return jsonify({
        "total_records": len(rows),
        "avg_session_duration": round(sum(r["duration_min"] for r in rows) / len(rows), 1) if rows else 0,
        "avg_distraction_duration": round(m["distract_time"] / max(1, m["distractions"]), 1),
        "most_common_category": most_common_cat,
        "correlation_labels": labels,
        "correlation_matrix": matrix,
        "label": "Real-Time Activity Data",
    })


