def compute_metrics(rows):
    if not rows:
        return dict(focus_time=0, distract_time=0, switches=0, avg_focus=0, distractions=0, focus_score=0)
    focus_time = sum(r["duration_min"] for r in rows if r["focus_level"] == "Focused")
    distract_time = sum(r["duration_min"] for r in rows if r["focus_level"] == "Distracted")
    distractions = sum(1 for r in rows if r["focus_level"] == "Distracted")
    focus_sessions = [r["duration_min"] for r in rows if r["focus_level"] == "Focused"]
    avg_focus = round(sum(focus_sessions) / len(focus_sessions), 1) if focus_sessions else 0
    switches = max(0, len(rows) - 1)
    total = focus_time + distract_time
    focus_score = round((focus_time / total) * 100) if total else 0
    return dict(
        focus_time=round(focus_time), distract_time=round(distract_time), switches=switches,
        avg_focus=avg_focus, distractions=distractions, focus_score=focus_score,
    )


