WEEKLY_MIN_TRACKED_MIN = 10   # min Focused+Distracted minutes needed in a period to compare
WEEKLY_MIN_DAY_TRACKED_MIN = 5  # min tracked minutes for a day to count as best/worst day


def _tracked_minutes(rows):
    """Return (focused_min, distracted_min) summed from Focused / Distracted rows."""
    focused = sum(float(r["duration_min"] or 0) for r in rows if r["focus_level"] == "Focused")
    distracted = sum(float(r["duration_min"] or 0) for r in rows if r["focus_level"] == "Distracted")
    return focused, distracted


def _focus_score_pct(rows):
    """Focused share of tracked (Focused + Distracted) time, 0-100, or None if no tracked time."""
    focused, distracted = _tracked_minutes(rows)
    total = focused + distracted
    return (focused / total * 100.0) if total > 0 else None


def build_weekly_report(rows, now=None):
    """
    Summarise the last 7 days and compare them with the 7 days before.

    Current period  : timestamp >= now - 7 days
    Previous period : now - 14 days <= timestamp < now - 7 days
    (ISO timestamp strings compared at minute precision.)

    The focus-score change is reported in percentage points and only when BOTH
    periods contain at least WEEKLY_MIN_TRACKED_MIN tracked minutes; otherwise
    the comparison is reported as unavailable, with the reason.
    """
    now = now or datetime.now()
    cur_start = (now - timedelta(days=7)).isoformat(timespec="minutes")
    prev_start = (now - timedelta(days=14)).isoformat(timespec="minutes")

    cur_rows = [r for r in rows if r["timestamp"] >= cur_start]
    prev_rows = [r for r in rows if prev_start <= r["timestamp"] < cur_start]

    report = {
        "has_data": bool(cur_rows),
        "period_start": cur_start,
        "previous_period_start": prev_start,
        "label": "Real-Time Activity Data",
    }

    if not cur_rows:
        report.update({
            "total_focus_time_min": 0, "total_distraction_time_min": 0,
            "avg_focus_session_min": 0, "distraction_events": 0,
            "most_distracting_category": None, "best_day": None, "worst_day": None,
            "comparison_available": False, "focus_score_change_pp": None,
            "current_focus_score": None, "previous_focus_score": None,
            "comparison_note": "No activity was recorded in the last 7 days.",
        })
        return report

    m = compute_metrics(cur_rows)

    # Best / worst day by focus share of tracked time (days with enough tracked time only)
    by_day = {}
    for r in cur_rows:
        by_day.setdefault(r["timestamp"][:10], []).append(r)
    day_scores = {}
    for day, day_rows in by_day.items():
        f, d = _tracked_minutes(day_rows)
        if f + d >= WEEKLY_MIN_DAY_TRACKED_MIN:
            day_scores[day] = f / (f + d) * 100.0
    if len(day_scores) >= 2:
        best_day = max(day_scores, key=day_scores.get)
        worst_day = min(day_scores, key=day_scores.get)
    else:
        best_day = worst_day = None

    cat_time = {}
    for r in cur_rows:
        if r["focus_level"] == "Distracted":
            cat_time[r["category"]] = cat_time.get(r["category"], 0) + float(r["duration_min"] or 0)
    most_distracting = max(cat_time, key=cat_time.get) if cat_time else None

    cur_f, cur_d = _tracked_minutes(cur_rows)
    prev_f, prev_d = _tracked_minutes(prev_rows)
    cur_score = _focus_score_pct(cur_rows)
    prev_score = _focus_score_pct(prev_rows)

    if prev_f + prev_d < WEEKLY_MIN_TRACKED_MIN:
        available, change, note = False, None, (
            "Previous-week comparison unavailable: fewer than "
            f"{WEEKLY_MIN_TRACKED_MIN} tracked minutes were recorded in the preceding 7 days."
        )
    elif cur_f + cur_d < WEEKLY_MIN_TRACKED_MIN:
        available, change, note = False, None, (
            "Comparison unavailable: fewer than "
            f"{WEEKLY_MIN_TRACKED_MIN} tracked minutes were recorded in the last 7 days."
        )
    else:
        available = True
        change = round(cur_score - prev_score, 1)
        note = "Change in focus score (percentage points) versus the previous 7 days."

    report.update({
        "total_focus_time_min": m["focus_time"],
        "total_distraction_time_min": m["distract_time"],
        "avg_focus_session_min": m["avg_focus"],
        "distraction_events": m["distractions"],
        "most_distracting_category": most_distracting,
        "best_day": best_day,
        "worst_day": worst_day,
        "comparison_available": available,
        "focus_score_change_pp": change,
        "current_focus_score": round(cur_score, 1) if cur_score is not None else None,
        "previous_focus_score": round(prev_score, 1) if available else None,
        "comparison_note": note,
    })
    return report


